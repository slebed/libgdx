#!/usr/bin/env python3
"""Generates VulkanDesktopInput.java from libGDX's DefaultLwjgl3Input.java (Apache-2.0).

The stock class needs an Lwjgl3Window, whose constructor is package-private and whose graphics object creates an OpenGL context; this
renderer has neither. The generated copy talks to a small DesktopInputHost interface instead (window handle, requestRendering, back buffer size), and
is otherwise the stock input code: the same key mapping, event queue and polling behaviour.

Usage: tools/generate_desktop_input.py <path to DefaultLwjgl3Input.java> <output file>
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read().replace('\r\n', '\n')

src = src.replace('package com.badlogic.gdx.backends.lwjgl3;', 'package io.github.slebed.gdxvulkan.desktop;', 1)
src = src.replace('public class DefaultLwjgl3Input extends AbstractInput implements Lwjgl3Input {',
                  'public class VulkanDesktopInput extends AbstractInput implements DesktopInputPolling {', 1)
src = src.replace('DefaultLwjgl3Input', 'VulkanDesktopInput')
src = src.replace('final Lwjgl3Window window;', 'final DesktopInputHost window;')
src = src.replace('public VulkanDesktopInput (Lwjgl3Window window) {', 'public VulkanDesktopInput (DesktopInputHost window) {')
src = src.replace('window.getGraphics().requestRendering()', 'window.requestRendering()')
src = src.replace('window.getWindowHandle()', 'window.windowHandle()')
src = src.replace('window.getConfig().hdpiMode == HdpiMode.Pixels', 'window.hdpiPixels()')
for a, b in (('getBackBufferWidth', 'backBufferWidth'), ('getBackBufferHeight', 'backBufferHeight'),
             ('getLogicalWidth', 'logicalWidth'), ('getLogicalHeight', 'logicalHeight')):
    src = src.replace('window.getGraphics().' + a + '()', 'window.' + b + '()')
src = src.replace('import com.badlogic.gdx.graphics.glutils.HdpiMode;\n', '')
left = [l for l in src.split('\n') if 'Lwjgl3Window' in l or 'getGraphics' in l or 'getConfig' in l]
assert not left, 'unexpected stock references left: ' + repr(left)
header = '// Generated by tools/generate_desktop_input.py from libGDX\'s DefaultLwjgl3Input.java (Apache-2.0, see NOTICE). Do not edit: regenerate.\n'
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write(src.replace('/*******', header + '/*******', 1))
