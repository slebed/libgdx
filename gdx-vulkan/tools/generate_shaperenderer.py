#!/usr/bin/env python3
"""Generates VulkanShapeRenderer.java from libGDX's ShapeRenderer.java.

    python tools/generate_shaperenderer.py <path/to/ShapeRenderer.java> > <...>/g2d/VulkanShapeRenderer.java

Stock's shape geometry (lines, rects, circles, arcs, curves, boxes, cones, ...) is built entirely on the ImmediateModeRenderer interface, so the
class is copied as it is and only its construction changes: instead of ImmediateModeRenderer20 (GL programs and Meshes) it creates a
VulkanImmediateModeRenderer. The nested ShapeType enum comes along, so write VulkanShapeRenderer.ShapeType (plan, Phase 2: the 2D exceptions).
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()

src = src.replace('package com.badlogic.gdx.graphics.glutils;', '''// GENERATED by tools/generate_shaperenderer.py from libGDX ShapeRenderer.java (Apache-2.0). Do not edit; change VulkanImmediateModeRenderer.
// Only the class name and its constructors differ from stock.
package io.github.slebed.gdxvulkan.g2d;''', 1)
src = src.replace('import com.badlogic.gdx.graphics.GL20;', 'import com.badlogic.gdx.graphics.GL20;\nimport com.badlogic.gdx.graphics.glutils.ImmediateModeRenderer;\nimport io.github.slebed.gdxvulkan.GdxVkFrame;', 1)
src = src.replace('public class ShapeRenderer implements Disposable {', 'public class VulkanShapeRenderer implements Disposable {', 1)

ctor = re.search(r'\tpublic ShapeRenderer \(\) \{.*?matrixDirty = true;\n\t\}\n', src, flags=re.S)
assert ctor, 'constructors not found'
src = src[:ctor.start()] + '''	public VulkanShapeRenderer (GdxVkFrame frame) {
		this(frame, 5000);
	}

	public VulkanShapeRenderer (GdxVkFrame frame, int maxVertices) {
		renderer = new VulkanImmediateModeRenderer(frame, maxVertices);
		projectionMatrix.setToOrtho2D(0, 0, Gdx.graphics.getWidth(), Gdx.graphics.getHeight());
		matrixDirty = true;
	}
''' + src[ctor.end():]
assert 'ImmediateModeRenderer20' not in src, 'a reference to the GL renderer is left'
print(src, end='')
