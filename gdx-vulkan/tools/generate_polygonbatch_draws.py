#!/usr/bin/env python3
"""Generates VulkanPolygonSpriteBatchDraws.java: the draw(...) overloads of libGDX's PolygonSpriteBatch, copied verbatim.

    python tools/generate_polygonbatch_draws.py <path/to/PolygonSpriteBatch.java> > <...>/g2d/VulkanPolygonSpriteBatchDraws.java

Same idea as generate_spritebatch_draws.py: the vertex- and triangle-writing code is stock's own so the comparison with stock libGDX is
about the backend, not about a retyped copy. The text between the first draw overload and flush() is copied unchanged, except that reads
of the package-private fields of PolygonRegion and TextureRegion become the public getters.
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
start = re.search(r'\t@Override\s*\n\tpublic void draw \(PolygonRegion region, float x, float y\)', src).start()
end = re.search(r'\t@Override\s*\n\tpublic void flush \(\)', src).start()
body = src[start:end]

# Stock sits in the same package as PolygonRegion/TextureRegion and reads their package-private fields; we use the public getters.
body = re.sub(r'\bregion\.(vertices|triangles|textureCoords|region)\b', lambda m: 'region.get' + m.group(1)[0].upper() + m.group(1)[1:] + '()', body)
tr = {'texture': 'getTexture()', 'u': 'getU()', 'v': 'getV()', 'u2': 'getU2()', 'v2': 'getV2()', 'regionWidth': 'getRegionWidth()',
      'regionHeight': 'getRegionHeight()'}
body = re.sub(r'\bregion\.getRegion\(\)\.(texture|u2|v2|u|v|regionWidth|regionHeight)\b', lambda m: 'region.getRegion().' + tr[m.group(1)], body)
body = re.sub(r'\b(region|textureRegion)\.(texture|u2|v2|u|v|regionWidth|regionHeight)\b', lambda m: m.group(1) + '.' + tr[m.group(2)], body)

print('''// GENERATED by tools/generate_polygonbatch_draws.py from libGDX PolygonSpriteBatch.java (Apache-2.0). Do not edit; change VulkanPolygonSpriteBatch.
// The draw(...) methods below are libGDX's own (region field reads became getter calls).
package io.github.slebed.gdxvulkan.g2d;

import com.badlogic.gdx.graphics.Color;
import com.badlogic.gdx.graphics.Texture;
import com.badlogic.gdx.graphics.g2d.PolygonBatch;
import com.badlogic.gdx.graphics.g2d.PolygonRegion;
import com.badlogic.gdx.graphics.g2d.TextureRegion;
import com.badlogic.gdx.math.Affine2;
import com.badlogic.gdx.math.MathUtils;

/** The state the stock draw methods read and write, and the draw methods themselves. */
abstract class VulkanPolygonSpriteBatchDraws implements PolygonBatch {
	protected static final int VERTEX_SIZE = 2 + 1 + 2;
	protected static final int SPRITE_SIZE = 4 * VERTEX_SIZE; // a quad: four vertices

	/** Stock layout: x, y, packed colour, u, v per vertex. VulkanPolygonSpriteBatch expands them when it flushes. */
	protected float[] vertices;
	protected short[] triangles;
	protected int vertexIndex, triangleIndex;
	protected Texture lastTexture;
	protected float invTexWidth = 0, invTexHeight = 0;
	protected boolean drawing;
	protected float colorPacked = Color.WHITE_FLOAT_BITS;

	/** Called by the draw methods when the texture changes (stock flushes here; Tier A records a slot change instead). */
	protected abstract void switchTexture (Texture texture);
''' + body.rstrip() + '\n}')
sys.stderr.write('copied %d lines of draw methods\n' % body.count('\n'))
