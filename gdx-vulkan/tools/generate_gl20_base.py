#!/usr/bin/env python3
"""Generates VulkanGL20Base.java from libGDX's GL20.java so the shim always covers the whole interface.

    python tools/generate_gl20_base.py <path/to/GL20.java> > gdx-vulkan-core/src/main/java/io/github/slebed/gdxvulkan/gl/VulkanGL20Base.java

Every method throws "not supported" naming the GL call, except the pure-state calls below, which are accepted and ignored until the
ordered state stream (Phase 2) applies them. VulkanGL20 overrides what the backend really implements.
"""
import re
import sys

# State the Vulkan backend will apply through the command stream; accepted for now.
IGNORED_STATE = {
    'glBlendColor', 'glBlendEquation', 'glBlendEquationSeparate', 'glBlendFunc', 'glBlendFuncSeparate', 'glClear', 'glClearColor',
    'glClearDepthf', 'glClearStencil', 'glColorMask', 'glCullFace', 'glDepthFunc', 'glDepthMask', 'glDepthRangef', 'glDisable',
    'glEnable', 'glFinish', 'glFlush', 'glFrontFace', 'glHint', 'glLineWidth', 'glPolygonOffset', 'glSampleCoverage', 'glScissor',
    'glStencilFunc', 'glStencilFuncSeparate', 'glStencilMask', 'glStencilMaskSeparate', 'glStencilOp', 'glStencilOpSeparate',
    'glViewport',
}
DEFAULTS = {'int': '0', 'boolean': 'false', 'float': '0f', 'String': 'null', 'void': ''}


def main():
    src = open(sys.argv[1], encoding='utf-8').read()
    body = src[src.index('public interface GL20'):]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)  # drop comments
    methods = re.findall(r'public\s+(\w+)\s+(\w+)\s*\(([^)]*)\)\s*;', body, flags=re.S)
    out = []
    out.append('// GENERATED by tools/generate_gl20_base.py from libGDX GL20.java. Do not edit; override in VulkanGL20.')
    out.append('package io.github.slebed.gdxvulkan.gl;')
    out.append('')
    out.append('import com.badlogic.gdx.graphics.GL20;')
    out.append('import com.badlogic.gdx.utils.GdxRuntimeException;')
    out.append('')
    out.append('import java.nio.Buffer;')
    out.append('import java.nio.FloatBuffer;')
    out.append('import java.nio.IntBuffer;')
    out.append('')
    out.append('/** Every GL20 method: unsupported (throws) unless it is pure state, which is accepted and ignored for now. */')
    out.append('abstract class VulkanGL20Base implements GL20 {')
    out.append('    /** What stock libGDX code calls that gdx-vulkan does not do through GL: drawing, programs, vertex state. */')
    out.append('    protected static GdxRuntimeException unsupported(String call) {')
    out.append('        return new GdxRuntimeException("gdx-vulkan: " + call + " is not supported. Draw with the Vulkan batches (VulkanSpriteBatch, '
               'VulkanModelBatch, ...); the GL20 shim covers textures, buffers, framebuffers and ordered state only.");')
    out.append('    }')
    for ret, name, params in methods:
        params = re.sub(r'\s+', ' ', params.strip())
        out.append('')
        out.append('    @Override')
        if name in IGNORED_STATE:
            out.append('    public %s %s (%s) {' % (ret, name, params))
            out.append('        // state: accepted, applied by the command stream once it exists')
            out.append('    }')
        elif name == 'glGetError':
            out.append('    public int glGetError () {')
            out.append('        return GL_NO_ERROR;')
            out.append('    }')
        else:
            out.append('    public %s %s (%s) {' % (ret, name, params))
            out.append('        throw unsupported("%s");' % name)
            out.append('    }')
    out.append('}')
    print('\n'.join(out))
    sys.stderr.write('generated %d methods (%d state, rest unsupported)\n' % (len(methods), sum(1 for m in methods if m[1] in IGNORED_STATE)))


main()
