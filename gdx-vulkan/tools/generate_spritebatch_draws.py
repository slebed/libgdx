#!/usr/bin/env python3
"""Generates VulkanSpriteBatchDraws.java: the draw(...) overloads of libGDX's SpriteBatch, copied verbatim.

    python tools/generate_spritebatch_draws.py <path/to/SpriteBatch.java> > <...>/g2d/VulkanSpriteBatchDraws.java

The Gate 2 oracle is stock SpriteBatch, so the code that turns a draw call into vertices must be the stock code, not a retyped copy that
could drift. Everything that differs (what flush() does, what switching texture means, shaders, matrices) is hand-written in VulkanSpriteBatch.
The text between the first draw overload and flush() is copied unchanged, except that region.texture/u/v/u2/v2 become the public getters
(stock sits in TextureRegion's package and reads the package-private fields). libGDX is Apache-2.0, as is this project.
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
start = re.search(r'\t@Override\s*\n\tpublic void draw \(Texture texture, float x, float y, float originX', src).start()
end = re.search(r'\t@Override\s*\n\tpublic void flush \(\)', src).start()
body = src[start:end]
getters = {'texture': 'getTexture()', 'u': 'getU()', 'v': 'getV()', 'u2': 'getU2()', 'v2': 'getV2()'}
body = re.sub(r'\bregion\.(texture|u2|v2|u|v)\b', lambda m: 'region.' + getters[m.group(1)], body)

print('''// GENERATED by tools/generate_spritebatch_draws.py from libGDX SpriteBatch.java (Apache-2.0). Do not edit; change VulkanSpriteBatch.
// The draw(...) methods below are libGDX's own (region field reads became getter calls).
package io.github.slebed.gdxvulkan.g2d;

import com.badlogic.gdx.graphics.Color;
import com.badlogic.gdx.graphics.Texture;
import com.badlogic.gdx.graphics.g2d.Batch;
import com.badlogic.gdx.graphics.g2d.Sprite;
import com.badlogic.gdx.graphics.g2d.TextureRegion;
import com.badlogic.gdx.math.Affine2;
import com.badlogic.gdx.math.MathUtils;

/** The state the stock draw methods read and write, and the draw methods themselves. */
abstract class VulkanSpriteBatchDraws implements Batch {
	/** Stock layout: 4 vertices of x, y, packed colour, u, v. VulkanSpriteBatch expands them when it flushes. */
	protected float[] vertices;
	protected int idx = 0;
	protected Texture lastTexture = null;
	protected float invTexWidth = 0, invTexHeight = 0;
	protected boolean drawing = false;
	protected float colorPacked = Color.WHITE_FLOAT_BITS;

	/** Called by the draw methods when the texture changes (stock flushes here; Tier A records a slot change instead). */
	protected abstract void switchTexture (Texture texture);
''' + body.rstrip() + '\n}')
sys.stderr.write('copied %d lines of draw methods\n' % body.count('\n'))
